TIMES = ["07:00", "18:00", "21:00"]  # 日本時間 朝・夕方・夜


def schedule():
    slots = []
    d = dt.date(2026, 10, 1)
    while len(slots) < len(POSTS):
        for t in TIMES:
            slots.append(f"{d.isoformat()} {t}+09:00")
        d += dt.timedelta(days=1)
    return slots[: len(POSTS)]


def main():
    posts = ROOT / "posts"
    for (key, cap, tags, slides), when in zip(POSTS, schedule()):
        folder = posts / f"{when[:10]}-{when[11:13]}-{key}"
        if (folder / "post.json").exists():
            continue  # 既にある投稿は上書きしない（手で直した内容を守る）
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "post.json").write_text(json.dumps({
            "draft": False, "publish_at": when, "caption": cap + tags, "slides": slides,
        }, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(len(POSTS), "posts", schedule()[0], "→", schedule()[-1])


if __name__ == "__main__":
    main()
